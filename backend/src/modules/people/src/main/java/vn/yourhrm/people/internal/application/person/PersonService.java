    // ================================================================================================ matching (003)

    /**
     * Duplicate detection (BR-PPL-001, US-PPL-003) within the current tenant only. Blocking: same CCCD / CMND number,
     * or same passport number + nationality (on the person or as an active passport document). Warning: same tax code
     * (also against another person's 12-digit personal id) or same SI number.
     */
    @HrTransactional(readOnly = true)
    public MatchResult match(MatchQuery q) {
        return match(q, null);
    }

    private MatchResult match(MatchQuery q, UUID excludePersonId) {
        UUID t = support.tenant();
        Map<UUID, String> blocking = new LinkedHashMap<>();
        Map<UUID, String> warnings = new LinkedHashMap<>();
        if (q.nationalId() != null && !q.nationalId().isBlank() && q.nationalIdType() != null) {
            String n = PersonRules.nationalId(q.nationalIdType(), q.nationalId());
            String key = PersonRules.nationalIdKey(q.nationalIdType(), n, nationality(q.nationalityCode()));
            ids("select id from hr.person where tenant_id = :t and national_id_bidx = :b", cipher.blindIndex(t, key))
                    .forEach(id -> blocking.putIfAbsent(id, "NATIONAL_ID"));
            if ("PASSPORT".equals(q.nationalIdType())) {
                passportMatches(t, n, nationality(q.nationalityCode())).forEach(id -> blocking.putIfAbsent(id, "PASSPORT"));
            }
        }
        if (q.passportNo() != null && !q.passportNo().isBlank()) {
            String n = PersonRules.nationalId("PASSPORT", q.passportNo());
            String nat = nationality(q.nationalityCode());
            ids("select id from hr.person where tenant_id = :t and national_id_bidx = :b",
                    cipher.blindIndex(t, PersonRules.nationalIdKey("PASSPORT", n, nat)))
                    .forEach(id -> blocking.putIfAbsent(id, "PASSPORT"));
            passportMatches(t, n, nat).forEach(id -> blocking.putIfAbsent(id, "PASSPORT"));
        }
        if (q.taxCode() != null && !q.taxCode().isBlank()) {
            byte[] b = cipher.blindIndex(t, PersonRules.taxCode(q.taxCode()));
            ids("select id from hr.person where tenant_id = :t and (tax_code_bidx = :b or national_id_bidx = :b)", b)
                    .forEach(id -> warnings.putIfAbsent(id, "TAX_CODE"));
        }
        if (q.siNumber() != null && !q.siNumber().isBlank()) {
            ids("select id from hr.person where tenant_id = :t and si_number_bidx = :b",
                    cipher.blindIndex(t, PersonRules.siNumber(q.siNumber())))
                    .forEach(id -> warnings.putIfAbsent(id, "SI_NUMBER"));
        }
        if (excludePersonId != null) {
            blocking.remove(excludePersonId);
            warnings.remove(excludePersonId);
        }
        blocking.keySet().forEach(warnings::remove);
        return new MatchResult(candidates(blocking), candidates(warnings));
    }

    private List<UUID> passportMatches(UUID t, String number, String nationality) {
        return db.jdbc().sql("""
                        select distinct person_id from hr.person_identity_doc
                         where tenant_id = :t and doc_type = 'PASSPORT' and issuing_country_code = :c
                           and doc_no_bidx = :b and status in ('ACTIVE','EXPIRED')""")
                .param("t", t).param("c", nationality).param("b", cipher.blindIndex(t, number))
                .query(UUID.class).list();
    }

    private List<UUID> ids(String sql, byte[] bidx) {
        return db.jdbc().sql(sql).param("t", support.tenant()).param("b", bidx).query(UUID.class).list();
    }

    private List<Candidate> candidates(Map<UUID, String> found) {
        List<Candidate> out = new ArrayList<>();
        found.forEach((id, on) -> db.jdbc().sql("""
                        select p.full_name, extract(year from p.birth_date)::int as y,
                               coalesce((select array_agg(e.employee_no order by e.hire_date) from hr.employment e
                                          where e.tenant_id = p.tenant_id and e.person_id = p.id), '{}') as nos
                          from hr.person p where p.tenant_id = :t and p.id = :id""")
                .param("t", support.tenant()).param("id", id)
                .query((rs, n) -> new Candidate(id, rs.getString(1), (Integer) rs.getObject(2), on,
                        List.of((String[]) rs.getArray(3).getArray())))
                .optional().ifPresent(out::add));
        return out;
    }

    // ================================================================================================ create (002)

    /** Creates a person; a blocking match is 409 {@code duplicate-person}, unacknowledged warnings 409 too. */
    @HrTransactional
    public PersonView create(CreatePerson cmd) {
        CreateOrMatch r = createInternal(cmd, false);
        return find(r.personId()).orElseThrow();
    }

    /**
     * Hire wizard entry (US-PPL-018): returns the existing person on a blocking match (the wizard then offers
     * rehire / concurrent employment), else creates the person. Joins the caller's People transaction.
     */
    @HrTransactional
    public CreateOrMatch createOrMatch(CreatePerson cmd) {
        return createInternal(cmd, true);
    }

    private CreateOrMatch createInternal(CreatePerson cmd, boolean returnMatch) {
        UUID t = support.tenant();
        LocalDate today = support.today();
        PersonData d = validate(cmd.data(), today);
        Identifiers ids = cmd.identifiers() == null ? Identifiers.none() : cmd.identifiers();
        String source = cmd.source() == null ? "APP" : cmd.source();
        if (!SOURCES.contains(source)) {
            throw ApiException.unprocessable("invalid-source", "Source must be one of " + SOURCES);
        }
        MatchResult m = match(new MatchQuery(ids.nationalIdType(), ids.nationalId(), d.nationalityCode(), null,
                ids.taxCode(), ids.siNumber()), null);
        if (!m.blocking().isEmpty()) {
            if (returnMatch) {
                return new CreateOrMatch(m.blocking().getFirst().personId(), false, m);
            }
            throw new ApiException(HttpStatus.CONFLICT, "duplicate-person", "A person with the same national "
                    + "identifier already exists in this tenant (BR-PPL-001)",
                    Map.of("personId", m.blocking().getFirst().personId(), "matchedOn", m.blocking().getFirst().matchedOn()));
        }
        if (!m.warnings().isEmpty() && !cmd.acknowledgeWarnings()) {
            throw new ApiException(HttpStatus.CONFLICT, "possible-duplicate-person", "Persons with the same tax code or "
                    + "SI number exist; check the candidates and confirm (acknowledgeWarnings) to create a new person",
                    Map.of("candidates", m.warnings().stream().map(c -> Map.of("personId", c.personId(),
                            "matchedOn", c.matchedOn())).toList()));
        }
        UUID id = Ids.newId();
        Subject subject = Subject.person(t, id);
        Normalised n = normalise(ids, d.nationalityCode(), today);
        if (n.religion() != null) {
            // consent is checked for the new subject id: an import / handoff carries the registry's subject mapping
            support.requireConsent(id, PersonConsentRegistry.PURPOSE_RELIGION);
        }
        Map<String, Object> p = new LinkedHashMap<>();
        p.put("t", t);
        p.put("id", id);
        p.put("source", source);
        p.put("actor", support.actor());
        dataParams(p, d);
        int keyVersion = sealParams(p, subject, n);
        p.put("kv", keyVersion);
        p.put("nidType", n.nationalId() == null ? null : ids.nationalIdType());
        p.put("nidBidx", n.nationalId() == null ? null : cipher.blindIndex(t,
                PersonRules.nationalIdKey(ids.nationalIdType(), n.nationalId(), d.nationalityCode())));
        try {
            db.jdbc().sql("""
                            insert into hr.person (tenant_id, id, family_name, middle_name, given_name, full_name,
                                   latin_name, preferred_name, birth_date, gender_code, nationality_code, hi_facility_code,
                                   si_book_custody, national_id_type, national_id_enc, national_id_bidx, national_id_last4,
                                   tax_code_enc, tax_code_bidx, tax_code_last4, si_number_enc, si_number_bidx,
                                   si_number_last4, hi_card_no_enc, hi_card_no_last4, ethnicity_enc, religion_enc,
                                   subject_key_version, source, created_by, updated_by)
                            values (:t, :id, :family, :middle, :given, :full, :latin, :preferred, :birth, :gender, :nat,
                                    :hif, :custody, :nidType, :nidEnc, :nidBidx, :nidLast4, :taxEnc, :taxBidx, :taxLast4,
                                    :siEnc, :siBidx, :siLast4, :hiEnc, :hiLast4, :ethEnc, :relEnc, :kv, :source, :actor,
                                    :actor)""")
                    .params(p).update();
        } catch (DuplicateKeyException e) {
            throw ApiException.conflict("duplicate-person", "A person with the same national identifier already exists");
        }
        if (n.legacyTaxCode() != null) {
            keepLegacyTaxCode(id, n.legacyTaxCode(), null);
        }
        if (d.birthDate() != null) {
            specialStatuses.deriveAgeStatuses(id, d.birthDate(), d.genderCode(), false);
        }
        List<String> changed = new ArrayList<>(List.of("family_name", "given_name", "full_name", "nationality_code"));
        n.fieldNames().forEach(changed::add);
        if (d.birthDate() != null) {
            changed.add("birth_date");
        }
        outbox.publish(new PersonalDataChanged(t, id, today, changed, d.nationalityCode(), null, null, "PERSON_CREATED"));
        return new CreateOrMatch(id, true, m);
    }

    // ================================================================================================ update

    /** Replaces the non-P3 attributes (PUT); optimistic {@code version}. */
    @HrTransactional
    public PersonView update(UUID personId, int version, PersonData data) {
        support.requirePerson(PeoplePermissions.PERSON_UPDATE, personId);
        LocalDate today = support.today();
        PersonData d = validate(data, today);
        PersonData before = loadData(personId);
        Map<String, Object> p = new LinkedHashMap<>();
        p.put("t", support.tenant());
        p.put("id", personId);
        p.put("v", version);
        p.put("actor", support.actor());
        dataParams(p, d);
        int updated = db.jdbc().sql("""
                        update hr.person set family_name = :family, middle_name = :middle, given_name = :given,
                               full_name = :full, latin_name = :latin, preferred_name = :preferred, birth_date = :birth,
                               gender_code = :gender, nationality_code = :nat, hi_facility_code = :hif,
                               si_book_custody = :custody, version = version + 1, updated_by = :actor
                         where tenant_id = :t and id = :id and version = :v and not is_anonymised""")
                .params(p).update();
        PersonSupport.requireUpdated(updated, "Person", personId);
        List<String> changed = diff(before, d);
        if (changed.contains("birth_date") || changed.contains("gender_code")) {
            specialStatuses.deriveAgeStatuses(personId, d.birthDate(), d.genderCode(), true);
        }
        if (!changed.isEmpty()) {
            outbox.publish(new PersonalDataChanged(support.tenant(), personId, today, changed,
                    changed.contains("nationality_code") ? d.nationalityCode() : null, null, null, "PERSON_UPDATED"));
        }
        return find(personId).orElseThrow();
    }

    /** Sets / clears P3 identifiers (US-PPL-002/008/009); a national-id change is re-checked for duplicates. */
    @HrTransactional
    public PersonView changeIdentifiers(UUID personId, int version, IdentifierChange change) {
        support.requirePerson(PeoplePermissions.PERSON_UPDATE, personId);
        UUID t = support.tenant();
        LocalDate today = support.today();
        Identifiers s = change.set() == null ? Identifiers.none() : change.set();
        Set<Field> clear = change.clear() == null || change.clear().isEmpty() ? Set.of() : EnumSet.copyOf(change.clear());
        record Current(String nationality, String nidType, byte[] taxEnc, int kv) {
        }
        Current cur = db.jdbc().sql("""
                        select nationality_code, national_id_type, tax_code_enc, subject_key_version from hr.person
                         where tenant_id = :t and id = :id and version = :v and not is_anonymised for update""")
                .param("t", t).param("id", personId).param("v", version)
                .query((rs, n) -> new Current(rs.getString(1), rs.getString(2), rs.getBytes(3), rs.getInt(4)))
                .optional().orElseThrow(() -> ApiException.conflict("stale-version",
                        "Person " + personId + " was changed meanwhile; reload and retry"));
        if (s.nationalId() != null) {
            String type = s.nationalIdType() != null ? s.nationalIdType() : cur.nidType();
            MatchResult m = match(new MatchQuery(type, s.nationalId(), cur.nationality(), null, null, null), personId);
            if (!m.blocking().isEmpty()) {
                throw new ApiException(HttpStatus.CONFLICT, "duplicate-person", "Another person of this tenant has "
                        + "the same national identifier (BR-PPL-001)", Map.of("personId", m.blocking().getFirst().personId()));
            }
        }
        Identifiers effective = new Identifiers(s.nationalId() != null && s.nationalIdType() == null ? cur.nidType()
                : s.nationalIdType(), s.nationalId(), s.taxCode(), s.legacyTaxCode(), s.siNumber(), s.hiCardNo(),
                s.ethnicityCode(), s.religionCode());
        Normalised n = normaliseForChange(effective, cur.nationality(), today);
        if (n.religion() != null) {
            support.requireConsent(personId, PersonConsentRegistry.PURPOSE_RELIGION);
        }
        Subject subject = Subject.person(t, personId);
        List<String> sets = new ArrayList<>();
        Map<String, Object> p = new LinkedHashMap<>();
        int kv = cur.kv();
        if (n.nationalId() != null) {
            Sealed sealed = cipher.encrypt(subject, "national_id", n.nationalId());
            kv = sealed.keyVersion();
            sets.add("national_id_type = :nidType, national_id_enc = :nidEnc, national_id_bidx = :nidBidx, national_id_last4 = :nidLast4");
            p.put("nidType", effective.nationalIdType());
            p.put("nidEnc", sealed.ciphertext());
            p.put("nidBidx", cipher.blindIndex(t, PersonRules.nationalIdKey(effective.nationalIdType(), n.nationalId(),
                    cur.nationality())));
            p.put("nidLast4", PiiCipher.last4(n.nationalId()));
        } else if (clear.contains(Field.NATIONAL_ID)) {
            sets.add("national_id_type = null, national_id_enc = null, national_id_bidx = null, national_id_last4 = null");
        }
        String oldTax = cur.taxEnc() == null ? null : cipher.decrypt(subject, "tax_code", cur.taxEnc(), cur.kv());
        if (n.taxCode() != null) {
            Sealed sealed = cipher.encrypt(subject, "tax_code", n.taxCode());
            kv = sealed.keyVersion();
            sets.add("tax_code_enc = :taxEnc, tax_code_bidx = :taxBidx, tax_code_last4 = :taxLast4");
            p.put("taxEnc", sealed.ciphertext());
            p.put("taxBidx", cipher.blindIndex(t, n.taxCode()));
            p.put("taxLast4", PiiCipher.last4(n.taxCode()));
        } else if (clear.contains(Field.TAX_CODE)) {
            sets.add("tax_code_enc = null, tax_code_bidx = null, tax_code_last4 = null");
        }
        boolean taxChanged = (n.taxCode() != null && !n.taxCode().equals(oldTax)) || clear.contains(Field.TAX_CODE);
        if (taxChanged && PersonRules.isLegacyTaxCode(oldTax)) {
            keepLegacyTaxCode(personId, oldTax, today);       // BR-PPL-013: the old 10-digit MST stays as history
        }
        if (n.legacyTaxCode() != null) {
            keepLegacyTaxCode(personId, n.legacyTaxCode(), null);
        }
        kv = sealOrClear(sets, p, subject, "si_number", n.siNumber(), clear.contains(Field.SI_NUMBER), true, kv);
        kv = sealOrClear(sets, p, subject, "hi_card_no", n.hiCardNo(), clear.contains(Field.HI_CARD_NO), false, kv);
        kv = sealOrClear(sets, p, subject, "ethnicity", n.ethnicity(), clear.contains(Field.ETHNICITY), false, kv);
        kv = sealOrClear(sets, p, subject, "religion", n.religion(), clear.contains(Field.RELIGION), false, kv);
        if (sets.isEmpty()) {
            return find(personId).orElseThrow();
        }
        p.put("t", t);
        p.put("id", personId);
        p.put("kv", kv);
        p.put("actor", support.actor());
        try {
            db.jdbc().sql("update hr.person set " + String.join(", ", sets)
                            + ", subject_key_version = :kv, version = version + 1, updated_by = :actor"
                            + " where tenant_id = :t and id = :id")
                    .params(p).update();
        } catch (DuplicateKeyException e) {
            throw ApiException.conflict("duplicate-person", "Another person has the same national identifier");
        }
        List<String> changed = new ArrayList<>(n.fieldNames());
        clear.forEach(f -> changed.add(f.name().toLowerCase(java.util.Locale.ROOT)));
        outbox.publish(new PersonalDataChanged(t, personId, today, List.copyOf(new LinkedHashSet<>(changed)), null,
                null, null, "IDENTIFIERS_UPDATED"));
        return find(personId).orElseThrow();
    }

    private int sealOrClear(List<String> sets, Map<String, Object> p, Subject subject, String column, String value,
            boolean clear, boolean hasBidx, int kv) {
        if (value != null) {
            Sealed sealed = cipher.encrypt(subject, column, value);
            sets.add(column + "_enc = :" + column + "Enc" + (hasBidx ? ", " + column + "_bidx = :" + column + "Bidx" : "")
                    + (hasLast4(column) ? ", " + column + "_last4 = :" + column + "Last4" : ""));
            p.put(column + "Enc", sealed.ciphertext());
            if (hasBidx) {
                p.put(column + "Bidx", cipher.blindIndex(subject.tenantId(), value));
            }
            if (hasLast4(column)) {
                p.put(column + "Last4", PiiCipher.last4(value));
            }
            return sealed.keyVersion();
        }
        if (clear) {
            sets.add(column + "_enc = null" + (hasBidx ? ", " + column + "_bidx = null" : "")
                    + (hasLast4(column) ? ", " + column + "_last4 = null" : ""));
        }
        return kv;
    }

    private static boolean hasLast4(String column) {
        return column.equals("si_number") || column.equals("hi_card_no");
    }

    // ================================================================================================ read / unmask

    /** The masked person (US-PPL-085); scope: any employment of the person, or tenant-wide for one without. */
    @HrTransactional(readOnly = true)
    public PersonView get(UUID personId) {
        support.requirePerson(PeoplePermissions.EMPLOYEE_VIEW, personId);
        masking.apply(PeoplePermissions.EMPLOYEE_VIEW);
        return find(personId).orElseThrow(() -> ApiException.notFound("Person", personId));
    }

    /** The masked person without permission checks (callers did them); the current mask level applies. */
    @HrTransactional(readOnly = true)
    public Optional<PersonView> find(UUID personId) {
        return db.jdbc().sql("""
                        select p.*, m.birth_date as masked_birth_date from hr.person p
                          join hr.v_person_masked m on m.tenant_id = p.tenant_id and m.id = p.id
                         where p.tenant_id = :t and p.id = :id""")
                .param("t", support.tenant()).param("id", personId)
                .query((rs, n) -> view(rs)).optional();
    }

    private PersonView view(ResultSet rs) throws SQLException {
        UUID id = rs.getObject("id", UUID.class);
        boolean religion = rs.getBytes("religion_enc") != null
                && support.hasConsent(id, PersonConsentRegistry.PURPOSE_RELIGION);
        return new PersonView(id, rs.getString("family_name"), rs.getString("middle_name"), rs.getString("given_name"),
                rs.getString("full_name"), rs.getString("latin_name"), rs.getString("preferred_name"),
                rs.getObject("masked_birth_date", LocalDate.class), rs.getString("gender_code"),
                rs.getString("nationality_code"), rs.getString("national_id_type"), masked(rs, "national_id_last4"),
                masked(rs, "tax_code_last4"), masked(rs, "si_number_last4"), masked(rs, "hi_card_no_last4"),
                rs.getString("hi_facility_code"), rs.getString("si_book_custody"), rs.getBytes("ethnicity_enc") != null,
                religion, rs.getString("verification_status"), rs.getString("source"), rs.getBoolean("is_anonymised"),
                rs.getInt("version"));
    }

    private static String masked(ResultSet rs, String last4Column) throws SQLException {
        String last4 = rs.getString(last4Column);
        return last4 == null ? null : "••••" + last4;
    }

    /**
     * Shows P3 values of a person (US-PPL-085): needs {@code hr.person.view_sensitive} in scope and a purpose; every
     * use is audited (who, when, which fields, purpose). Religion is withheld without the person's consent.
     */
    @HrTransactional(readOnly = true)
    public Unmasked unmask(UUID personId, Set<Field> fields, String purpose) {
        if (purpose == null || purpose.isBlank()) {
            throw ApiException.unprocessable("purpose-required", "Unmasking needs a purpose (BR-PPL-152)");
        }
        support.requirePerson(PeoplePermissions.PERSON_VIEW_SENSITIVE, personId);
        UUID t = support.tenant();
        Subject subject = Subject.person(t, personId);
        Map<String, String> out = new LinkedHashMap<>();
        List<String> withheld = new ArrayList<>();
        db.jdbc().sql("select * from hr.person where tenant_id = :t and id = :id")
                .param("t", t).param("id", personId)
                .query(rs -> {
                    int kv = rs.getInt("subject_key_version");
                    for (Field f : EnumSet.copyOf(nonEmpty(fields))) {
                        switch (f) {
                            case BIRTH_DATE -> out.put(f.name(), Objects.toString(rs.getObject("birth_date", LocalDate.class), null));
                            case RELIGION -> {
                                if (support.hasConsent(personId, PersonConsentRegistry.PURPOSE_RELIGION)) {
                                    out.put(f.name(), cipher.decrypt(subject, "religion", rs.getBytes("religion_enc"), kv));
                                } else {
                                    withheld.add(f.name());
                                }
                            }
                            default -> {
                                String col = f.name().toLowerCase(java.util.Locale.ROOT);
                                out.put(f.name(), cipher.decrypt(subject, col, rs.getBytes(col + "_enc"), kv));
                            }
                        }
                    }
                });
        sensitive.recordSensitiveRead(PeoplePermissions.PERSON_VIEW_SENSITIVE, "hr.person", personId, null);
        audit.record(new AuditLog.BusinessAction("UNMASK", "hr", "person", personId, null,
                Map.of("fields", String.join(",", out.keySet()), "purpose", purpose.trim())));
        return new Unmasked(personId, out, withheld);
    }

